-- ===========================================================================
-- PlayerBot names: the Trilogy client's own Random Name generator
--
-- Recovered from eqgame.exe (v29c, 22 Aug 2001): the character-creation
-- Random Name button calls 0x4af3d7(race, female). This file carries its data;
-- zone/playerbot_namegen.cpp (PlayerBotClientNameGen) carries the algorithm.
--
--   playerbot_client_name_parts  the client's pointer table at 0x566838:
--       per race, 5 slots x 10 rows. A name is slot0 + [slot1] + [slot2] +
--       slot3 + [slot4]; slots 1 and 2 are taken 80/101 of the time, slot 4
--       (the vowel endings) only for female characters, each slot's row rolled
--       independently.
--   playerbot_client_name_bans   race N: substrings the client rejects for that
--       race (table at 0x5673f0), matched case-SENSITIVELY. race 0: the
--       client's every-race list (0x5679d0), matched case-insensitively.
--
-- Validated against the 133 character names in a live client folder: the
-- 114 not obviously typed by hand are all producible by this grammar.
--
-- playerbot_races.client_name_chance (NULL = rule PlayerBots:ClientNameChance)
-- is the % of that race's PlayerBots named this way instead of by the
-- playerbot_name_sets generator, which still covers anything this one cannot.
-- 0 turns it off for the race, 100 makes it the only source.
--
-- Run after the other 2026_10_18_bots_playerbot_native*.sql files.
-- Re-runnable. Takes effect after #pbnative reload or the zone's next boot.
-- ===========================================================================

SELECT COUNT(*) AS client_name_tables_already_present
FROM information_schema.tables
WHERE table_schema = DATABASE()
  AND table_name IN ('playerbot_client_name_parts', 'playerbot_client_name_bans');

CREATE TABLE IF NOT EXISTS playerbot_client_name_parts (
  race       SMALLINT UNSIGNED NOT NULL,   -- EQ race id (1-12, 128 Iksar, 130 Vah Shir)
  slot       TINYINT UNSIGNED NOT NULL,    -- 0..4, see above
  row_index  TINYINT UNSIGNED NOT NULL,
  part       VARCHAR(16) NOT NULL,
  PRIMARY KEY (race, slot, row_index)
);

CREATE TABLE IF NOT EXISTS playerbot_client_name_bans (
  race     SMALLINT UNSIGNED NOT NULL,     -- 0 = every race (case-insensitive)
  pattern  VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
  PRIMARY KEY (race, pattern)
);

ALTER TABLE playerbot_races
  ADD COLUMN IF NOT EXISTS client_name_chance TINYINT UNSIGNED NULL DEFAULT NULL;

DELETE FROM playerbot_client_name_parts;
DELETE FROM playerbot_client_name_bans;

