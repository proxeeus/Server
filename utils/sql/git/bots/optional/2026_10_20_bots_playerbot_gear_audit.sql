-- ===========================================================================
-- PlayerBot gear audit (2026-10-20): class/race-legal pools + P99 era gear
--
-- Run AFTER 2026_10_18_bots_playerbot_native.sql and ..._native_gear.sql.
-- That gear file EMPTIES and reloads both gear tables, so re-running it undoes
-- this file -- run this one again afterwards. Every statement here is
-- re-runnable (guarded on current values / INSERT IGNORE / exact pairs).
--
-- Back up first:
--   mysqldump proxeeus_db playerbot_gear_draws playerbot_gear_items \
--     playerbot_class_races playerbot_lore_classes > pb_gear_backup.sql
--   mysqldump proxeeus_db items --where="id=119466" > item_119466_backup.sql
