-- Six tiers, each independent; skip any. Each has a dry-run SELECT, the change,
-- and an expect_ SELECT. Takes effect after `#pbnative reload` (or zone boot);
-- tier 2 (an items row) also needs shared_memory to be re-run.
--
-- Pairs with zone/playerbot_native.cpp ApplyGear picking only items whose
-- items.classes / items.races allow the bot. That alone stops illegal gear;
-- these tiers remove the dead rows and give the pools real era gear.
-- Sources: Project 1999 wiki (classes/races checked for every item added).
-- No raid gear: no planar, Trakanon/Venril/VP/ST, Kael, ToV, faction-armor
-- quests; Kunark class armor only its non-breastplate/non-greaves pieces.
-- ===========================================================================


