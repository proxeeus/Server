-- ============================================================================
-- Trilogy: classic weapon models for the v29c client
-- ============================================================================
--
-- The v29c client takes a held weapon's model as ONE BYTE (Spawn_Struct
-- equipment[7..8], WearChange_Struct slot_graphic) and as a 5-character
-- ClassicItem_Struct.idfile string for the player's own hands.  Modern item
-- data gives many classic items revamped models such as IT10650, which wrap to
-- an unrelated classic model (10650 & 0xFF = 154 = Spear of Fate) or truncate
-- to another ("IT106" = Sarnak Ceremonial Sword).  The client only has IT1-IT228
-- and IT250 to hold (pulled from gequip.s3d / gequip2.s3d).
--
-- These two tables let the Trilogy wire code send a classic model instead.
-- The `items` table is NOT touched: Titanium and later clients keep the modern
-- models.  See common/patches/trilogy_weapon_models.cpp for the lookup order:
--
--   1. trilogy_item_models  item id -> classic model (era-correct, per item)
--   2. trilogy_model_map    modern model -> classic model (per model)
--   3. a per-item-type default in code (1HS -> IT1, piercing -> IT5, ...)
--   4. nothing in hand
--
-- A model the client already has is always sent unchanged, so nothing that
-- displays correctly today can change.
--
-- Seed data
--   trilogy_item_models: every primary/secondary item whose current model the
--     client lacks, taking the classic idfile from the p2002 database (same
--     item ids).  IT63 is skipped (classic data uses it as a placeholder; the
--     item-type default gives a better answer), as is Fabled Short Sword of
--     Flame's IT67 (an idol model on a sword).  512 rows.
--   trilogy_model_map: for each modern model, the classic model most items with
--     that modern model had in p2002 (note = items agreeing / items compared).
--     Only models with at least 3 items compared: one item is not enough to
--     speak for every item sharing its model (IT10024 is ~20 short swords; its
--     one p2002 pair said IT67, an idol).  Three extra rows for models
--     npc_types uses with no p2002 pair, mapped by the item type of the items
--     that carry the model.
--
-- Editing: add or change rows, then restart the zone (and world, for the
-- character select screen).  Tables are read once per process.
--
-- Creates two tables and inserts with INSERT IGNORE: touches nothing that
-- exists, keeps your own edits on a re-run.
-- ============================================================================

CREATE TABLE IF NOT EXISTS `trilogy_item_models` (
  `item_id` int(10) unsigned     NOT NULL,
  `model`   smallint(5) unsigned NOT NULL,
  `note`    varchar(128)         NOT NULL DEFAULT '',
  PRIMARY KEY (`item_id`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

CREATE TABLE IF NOT EXISTS `trilogy_model_map` (
  `model`         int(10) unsigned     NOT NULL,
  `classic_model` smallint(5) unsigned NOT NULL,
  `note`          varchar(128)         NOT NULL DEFAULT '',
  PRIMARY KEY (`model`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;

